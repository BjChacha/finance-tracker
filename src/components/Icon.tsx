export type IconName = keyof typeof REGISTRY;

type IconProps = {
  name: IconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
  style?: ViewStyle;
  testID?: string;
};

/** 图标渲染入口。color 由调用方按主题传入（如 colors.text / colors.primary）。 */
export function Icon({ name, size = 24, color, strokeWidth, style, testID }: IconProps) {
  const Cmp = REGISTRY[name];
  return <Cmp size={size} color={color} strokeWidth={strokeWidth} style={style} testID={testID} />;
}
